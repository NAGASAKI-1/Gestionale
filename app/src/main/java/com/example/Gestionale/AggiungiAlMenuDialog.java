    private void bImmagineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bImmagineActionPerformed
        int returnVal = jFileChooser1.showOpenDialog(this);
        if (returnVal == JFileChooser.APPROVE_OPTION) { //Se viene scelto un file
            File immagineIntera = jFileChooser1.getSelectedFile();
            Image tempImg = null;
            
            try {
                //ridimensionamento immagine
                tempImg = ImageIO.read(immagineIntera).getScaledInstance(120, 120, Image.SCALE_SMOOTH);   //Riduce (o aumenta) la dimensione dell'immagine in modo che entri nel JButton            
                bufferedImage = new BufferedImage(120, 120, BufferedImage.TYPE_INT_ARGB);    //https://www.baeldung.com/java-image-bufferedimage-conversion
                bufferedImage.getGraphics().drawImage(tempImg, 0, 0, null);
                immagineCambiata = true;
            } catch (IOException ex) {
                System.out.println(ex);
                JOptionPane.showMessageDialog(this, "Si è verificato un problema aprendo il file.", "ERRORE", JOptionPane.WARNING_MESSAGE);
            }
            
            bImmagine.setIcon(new ImageIcon(tempImg));
            bImmagine.setText(null);
        } else {
            System.out.println("Selezione icona: operazione annullata dall'utente");
        }
    }//GEN-LAST:event_bImmagineActionPerformed

