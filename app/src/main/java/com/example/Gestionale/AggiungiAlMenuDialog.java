    private void bConfermaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bConfermaActionPerformed
        pietanza.setAllergeni(taAllergeni.getText());
        pietanza.setIngredienti(taIngredienti.getText());
        pietanza.setNomePietanza(tfNomePietanza.getText());
        pietanza.setNote(taAltreNote.getText());
        pietanza.setSenzaGlutine(cbSenzaGlutine.isSelected());
        pietanza.setSenzaLattosio(cbSenzaLattosio.isSelected());
        pietanza.setVegetariano(cbVegetariano.isSelected());
        pietanza.setVegano(cbVegano.isSelected());
        pietanza.setPortata((Portata) cbPortata.getSelectedItem());
        try {
            pietanza.setPrezzo(Float.parseFloat(tfPrezzo.getText()));
        }
        catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Inserire un prezzo valido. Assicurati di usare il punto al posto della virgola.", "Errore prezzo", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (immagineCambiata) {
            try {
                File file = new File(String.format("./src/main/resources/ImmaginiPietanze/immagine_scalata_%s_%s-%s.png", pietanza.getNomePietanza(), LocalDate.now(), LocalTime.now()));
                ImageIO.write(bufferedImage, "PNG", file);
                pietanza.setPathImmagine(file.getAbsolutePath());
            } catch(IOException ex) {
                JOptionPane.showMessageDialog(this, "L'immagine non è stata scelta o qualcosa è andato storto nel salvataggio dell'immagine su disco", "Errore IO", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        
        
        returnValue = CONFERMA;
        
        this.setVisible(false);
        this.dispose();
    }//GEN-LAST:event_bConfermaActionPerformed

