    private void formWindowClosing(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowClosing
        try{
            tavolo.setNumTavolo(Integer.parseInt(tfNumeroTavolo.getText()));
            tavolo.setNumPosti(Integer.parseInt(tfNumeroPosti.getText()));
            tavolo.setNumCoperti(Integer.parseInt(tfNumeroCoperti.getText()));
            tavolo.setStatoTavolo((StatoTavolo) cbStatoTavolo.getSelectedItem());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Alcuni dati del tavolo non sono stati aggiornati poichè la formattazione del testo è errata", "ERRORE", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_formWindowClosing

    private void bCalcolaTotaleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bCalcolaTotaleActionPerformed
        float tot = 0;
        
        for (Pietanza p : tavolo.getOrdine())
            tot += p.getPrezzo();
        
        try {
            tot += Float.parseFloat(tfNumeroCoperti.getText()) * tavolo.PREZZO_COPERTO;
            tfTotale.setText(Float.toString(tot));
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Assicurati di aver inserito un valore valido nel campo dei coperti", "ERRORE", JOptionPane.ERROR_MESSAGE);
            tfTotale.setText("0");
        }
    }//GEN-LAST:event_bCalcolaTotaleActionPerformed

