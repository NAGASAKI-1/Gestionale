    private void bSelezioneClicked(java.awt.event.MouseEvent evt) {
        //potrebbe essere conveniente processare tutti i panel all'apertura della finestra di ordinazione
        //per evitare overhead ogni volta che si preme un pulsante per cambiare categoria
        //ulteriore soluzione sarebbe cachare il panel già processati e ricaricarli se l'utente ritorna sulla categoria (da provare)
        menuScroller3.removeAllButtons();
        Portata portata = portataBottone.inverse().get(((JToggleButton) evt.getSource()).getModel()); //trova la portata corrispondente al bottone cliccato
        for (Pietanza i : menu) {
            if(i.getPortata() == portata) {
                menuScroller3.addMenu(new BottoneMenuOrdinazione(i, pietanzaAggiuntaListener));
            }
        }
        menuScroller3.revalidate();
        menuScroller3.repaint();
    }
    
    private void onPietanzaAggiunta(Pietanza p) {
        tavolo.getOrdine().add(p);
        jPanel1.add(new ElementoListaOrdinazione(p, pietanzaEliminataListener));
        jPanel1.revalidate();
        jPanel1.repaint();
        //System.out.println("OOOOOOH MY GOOOOD!!!");
    }
    
    private void onPietanzaEliminata(Pietanza p) {
        tavolo.getOrdine().remove(p);
    }
    
    
